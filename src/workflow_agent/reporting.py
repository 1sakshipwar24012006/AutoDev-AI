"""PR body generation and run artefacts (report.json, changes.patch, pr_body.md)."""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from workflow_agent.models import RunReport
from workflow_agent.security import redact


def build_pr_title(report: RunReport) -> str:
    issue = report.issue
    if issue is None:
        return "Automated fix"
    prefix = f"Fix #{issue.number}: " if issue.number is not None else "Fix: "
    return (prefix + issue.title)[:120]


def build_pr_body(report: RunReport) -> str:
    accepted = next((a for a in reversed(report.attempts) if a.stage_reached == "accepted"), None)
    lines: list[str] = ["## Summary", ""]
    if accepted and accepted.changeset:
        lines += [accepted.changeset.explanation.strip(), ""]
    if report.issue and report.issue.number is not None:
        lines += [f"Closes #{report.issue.number}", ""]
    if report.plan:
        lines += ["## Root cause", "", report.plan.root_cause.strip(), ""]
    if accepted and accepted.changeset:
        lines += ["## Changes", ""]
        for edit in accepted.changeset.edits:
            lines.append(f"- `{edit.path}` ({edit.operation})")
        lines.append("")
    lines += ["## Verification", ""]
    if report.baseline_tests:
        lines.append(f"- Baseline tests: {report.baseline_tests.short()}")
    if accepted and accepted.tests:
        lines.append(f"- Tests after change: {accepted.tests.short()}")
    lines.append(f"- Attempts used: {len(report.attempts)}")
    if accepted and accepted.review:
        lines += ["", "## AI self-review", "", accepted.review.summary.strip()]
        for c in accepted.review.concerns:
            lines.append(f"- **{c.severity}**: {c.message}")
    lines += [
        "",
        "---",
        "_Generated by autonomous-coding-workflow-agent. This pull request was not merged automatically; "
        "please review the changes carefully before merging._",
    ]
    return "\n".join(lines) + "\n"


def create_run_dir(base: Path, issue_number: int | None) -> tuple[str, Path]:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    suffix = f"issue-{issue_number}" if issue_number is not None else "local-issue"
    run_id = f"{stamp}-{suffix}"
    run_dir = base / run_id
    n = 2
    while run_dir.exists():
        run_dir = base / f"{run_id}-{n}"
        n += 1
    run_dir.mkdir(parents=True, exist_ok=True)
    return run_dir.name, run_dir


def write_artifacts(report: RunReport, run_dir: Path) -> None:
    (run_dir / "report.json").write_text(redact(report.model_dump_json(indent=2)), encoding="utf-8")
    diff = report.final_diff or next((a.diff for a in reversed(report.attempts) if a.diff), "")
    if diff:
        name = "changes.patch" if report.final_diff else "last_attempt_rejected.patch"
        (run_dir / name).write_text(diff, encoding="utf-8", newline="")
    if report.success:
        (run_dir / "pr_body.md").write_text(redact(build_pr_body(report)), encoding="utf-8")
